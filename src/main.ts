import 'reflect-metadata';
import { NestFactory } from '@nestjs/core';
import { ValidationPipe, Logger } from '@nestjs/common';
import { DocumentBuilder, SwaggerModule } from '@nestjs/swagger';
import cookieParser from 'cookie-parser';
import { AppModule } from './app.module';
import { HttpExceptionFilter } from './common/filters/http-exception.filter';

async function bootstrap() {
  const logger = new Logger('Bootstrap');
  const app = await NestFactory.create(AppModule, { cors: true });

  app.use(cookieParser());

  app.useGlobalPipes(
    new ValidationPipe({
      whitelist: true,
      transform: true,
      forbidNonWhitelisted: false,
      transformOptions: { enableImplicitConversion: true },
    }),
  );

  app.useGlobalFilters(new HttpExceptionFilter());

  const swaggerConfig = new DocumentBuilder()
    .setTitle('Dental Clinic WhatsApp Bot API')
    .setDescription(
      'Administrative and webhook API contracts for the WhatsApp AI dental assistant. ' +
        'Handles Meta WhatsApp Cloud API webhooks, clinic/insurance administration, and lead tracking.',
    )
    .setVersion('1.0.0')
    .addTag('Webhook', 'Meta WhatsApp Cloud API webhook handshake and events')
    .addTag('Admin - Dashboard UI', 'Interactive Admin Command Center UI')
    .addTag('Admin - Overview', 'High-level metrics and system stats')
    .addTag(
      'Admin - Agent Grounding',
      'Live prompt compilation and real-time agent verification',
    )
    .addTag('Admin - Clinics', 'Manage dental clinic records')
    .addTag('Admin - Insurance Plans', 'Manage insurance plan records')
    .addTag('Admin - Leads', 'View and manage leads generated by the bot')
    .addTag('Admin - Appointments', 'View and manage appointments')
    .addTag('Admin - Users', 'View patient profiles and full message histories')
    .build();

  const document = SwaggerModule.createDocument(app, swaggerConfig);
  SwaggerModule.setup('api/docs', app, document);

  const port = process.env.PORT ? parseInt(process.env.PORT, 10) : 80;
  await app.listen(port, '0.0.0.0');

  logger.log(`Application is running on: http://localhost:${port}`);
  logger.log(`Interactive Playground: http://localhost:${port}/playground`);
  logger.log(`Admin Command Center: http://localhost:${port}/admin/dashboard`);
  logger.log(`Swagger docs available at: http://localhost:${port}/api/docs`);
}

bootstrap();
